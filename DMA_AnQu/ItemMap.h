class ItemFilterTable {
public:
    static ItemFilterTable& Get() { static ItemFilterTable i; return i; }
    bool IsEnabled(const std::string& cn) const {
        if (!m_master) return false;
        auto it=m_t.find(cn); return it==m_t.end()?true:it->second;
    }
    void SetEnabled(const std::string& cn, bool v) { m_t[cn]=v; }
    void SetCategoryEnabled(const ItemCategory& cat, bool v) { for(auto& s:cat.items)m_t[s]=v; }
    void SetAllEnabled(bool v) { m_master=v; for(auto& c:kItemCategories)for(auto& s:c.items)m_t[s]=v; }
    void SetAllUnchecked() { for(auto& c:kItemCategories)for(auto& s:c.items)m_t[s]=false; }  // 只取消勾选, 不关master
    int CategoryCount(const ItemCategory& cat) const { int n=0; for(auto& s:cat.items)if(IsEnabled(s))n++; return n; }
    int TotalEnabled() const { int n=0; for(auto& c:kItemCategories)n+=CategoryCount(c); return n; }
    int TotalItems() const { int n=0; for(auto& c:kItemCategories)n+=(int)c.items.size(); return n; }
    int GetCategoryIndex(const std::string& cn) const { auto it=m_ci.find(cn); return it!=m_ci.end()?it->second:-1; }
    bool SaveConfig(const char* fn="item_filter.cfg") {
        FILE* fp=nullptr; fopen_s(&fp,fn,"w"); if(!fp)return false;
        fprintf(fp,"master=%d\n",m_master?1:0);
        for(auto& c:kItemCategories)for(auto& s:c.items)fprintf(fp,"%s=%d\n",s.c_str(),IsEnabled(s)?1:0);
        fclose(fp); return true;
    }
    bool LoadConfig(const char* fn="item_filter.cfg") {
        FILE* fp=nullptr; fopen_s(&fp,fn,"r"); if(!fp)return false;
        char line[512];
        while(fgets(line,sizeof(line),fp)){
            char* eq=strchr(line,'='); if(!eq)continue;
            *eq='\0'; std::string cn(line); bool v=(atoi(eq+1)!=0);
            if(cn=="master") m_master=v;
            else if(kItemNameMap.count(cn)) m_t[cn]=v;
        }
        fclose(fp); return true;
    }
private:
    ItemFilterTable(){SetAllEnabled(true);
        for(size_t ci=0;ci<kItemCategories.size();ci++)for(auto&s:kItemCategories[ci].items)m_ci[s]=(int)ci;}
    bool m_master=true;
    std::unordered_map<std::string,bool> m_t;
    std::unordered_map<std::string,int> m_ci; // className→categoryIndex
};

inline const char* GetItemDisplayName(const std::string& cn) {
    auto it=kItemNameMap.find(cn);
    return it!=kItemNameMap.end()?it->second.c_str():cn.c_str();
}

